function setLang(lang) {
    const t = T[lang];
    if (!t) return;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.title = t.page_title;
    document.querySelector('meta[name="description"]').setAttribute("content", t.page_desc);
    document.querySelector(".photo").alt = t.alt;
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
        const key = el.getAttribute("data-i18n");
        if (t[key] !== undefined) el.innerHTML = t[key];
    });
    document.querySelectorAll(".lang-switch button").forEach(function (b) {
        b.classList.toggle("active", b.dataset.lang === lang);
    });
    try { localStorage.setItem("lang", lang); } catch (e) { /* ignore */ }
}

document.querySelectorAll(".lang-switch button").forEach(function (b) {
    b.addEventListener("click", function () { setLang(b.dataset.lang); });
});

// Start language: saved choice, else browser language, else French
let start = "fr";
try { start = localStorage.getItem("lang") || ""; } catch (e) { start = ""; }
if (!T[start]) {
    const nav = (navigator.language || "fr").slice(0, 2);
    start = T[nav] ? nav : "fr";
}
setLang(start);
